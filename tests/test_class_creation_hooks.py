def test_only_the_first_mro_hook_executes_without_a_cooperative_super_call(tmp_path):
    text = SOURCE.replace('class Public(Base):', '''class Other:
    def __init_subclass__(cls): opaque(cls)
class Public(Base, Other):''')
    result, _ = analyze(tmp_path, text)
    assert len(result.inputs['entry_binding']['class_creation_hooks']) == 1


def test_ancestor_creation_phases_are_retained_without_duplicate_execution(tmp_path):
    text = SOURCE.replace('class Public(Base):', 'class Middle(Base): pass\nclass Public(Middle):')
    result, _ = analyze(tmp_path, text)
    hooks = result.inputs['entry_binding']['class_creation_hooks']
    assert [hook['receiver_class']['qualname'] for hook in hooks] == ['Middle', 'Public']


def test_a_class_constructor_call_uses_the_same_creation_effects(tmp_path):
    result, _ = analyze(tmp_path, SOURCE + '\ndef client(**kwargs): return Public(**kwargs)\n', 'client')
    call = next(call for call in result.calls if call.target and call.target.qualname == 'Public.__init__')
    assert call.constructor_bindings[0]['status'] == 'source_bound'
    assert call.constructor_bindings[0]['class_creation_hooks'][0]['attributes'] == ['marker']


def test_a_hook_method_override_cannot_keep_the_original_fresh_method_proof(tmp_path):
    text = SOURCE.replace('cls.marker = True', 'cls.dispatch = opaque')
    text = text.replace('def __init__(self, **kwargs): fixed(**kwargs)',
                        'def __init__(self, **kwargs): self.dispatch(**kwargs)\n'
                        '    def dispatch(self, **kwargs): fixed(**kwargs)')
    result, _ = analyze(tmp_path, text)
    call = next(call for call in result.calls if call.callee_name == 'self.dispatch')
    assert not call.instance_method_bindings


def test_new_hook_attributes_participate_in_the_static_member_namespace(tmp_path):
    text = SOURCE.replace('cls.marker = True', 'cls.injected = unknown_callable')
    text = text.replace('def __init__(self, **kwargs): fixed(**kwargs)', '''def __init__(self, **kwargs): self.update(kwargs)
    def update(self, properties):
        for key, value in properties.items():
            method = getattr(self, f'{key}', None)
            if not callable(method): raise AttributeError(key)
            method(value)''')
    result, _ = analyze(tmp_path, text)
    checks = [fact for summary in result.functions for fact in summary.get('fresh_mapping_member_checks', [])]
    assert checks and 'injected' in checks[0]['member_names']


