def test_classmethod_documentation_writes_can_expose_a_class_and_replace_its_allocator(tmp_path):
    text = '''class Base:
    def __init_subclass__(cls): cls.marker = True
    @classmethod
    def seed(cls): cls.method.__doc__ = cls
    def method(self):
        """Initially plain documentation."""
class Public(Base):
    def __init__(self, **kwargs): fixed(**kwargs)
def fixed(allowed=0): return allowed
def allocate(cls, **kwargs): return {'received': kwargs}
def expose(candidate): candidate.__new__ = allocate
Base.seed()
expose(Base.method.__doc__)
'''
    (tmp_path / 'example.py').write_text(text, encoding='utf-8')
    analyzer = FlowAnalyzer(project_root=tmp_path)
    with pytest.raises(ValueError):
        analyzer.analyze(FunctionRef('example', 'Public'))
    assert runpy.run_path(str(tmp_path / 'example.py'))['Public'](old=1) == {'received': {'old': 1}}
