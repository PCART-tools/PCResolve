def test_creation_hook_reads_method_metadata_from_a_prior_module_class_call(tmp_path):
    base = '''class Seed:
    @classmethod
    def initialize(cls): cls.set._autogenerated_signature = True
    def set(self, **kwargs): pass
Seed.initialize()
'''
    (tmp_path / 'base.py').write_text(base, encoding='utf-8')
    text = '''from base import Seed
class Base(Seed):
    def __init_subclass__(cls):
        if hasattr(cls.set, '_autogenerated_signature'): cls.marker = True
class Public(Base):
    def __init__(self, **kwargs): fixed(**kwargs)
def fixed(allowed=0): return allowed
'''
    result, _ = analyze(tmp_path, text)
    hook = result.inputs['entry_binding']['class_creation_hooks'][0]
    assert hook['attributes'] == ['marker']
    query, = [item for item in hook['class_metadata_queries']
              if item.get('kind') == 'source_bound_callable_metadata_presence']
    assert query['result'] is True
    assert query['metadata_fact']['kind'] == 'source_module_initialization_member_metadata'


