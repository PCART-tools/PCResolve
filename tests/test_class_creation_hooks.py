def test_explicit_builtin_classmethod_has_the_same_creation_receiver(tmp_path):
    result, _ = analyze(tmp_path, SOURCE.replace('    def __init_subclass__',
                                                  '    @classmethod\n    def __init_subclass__'))
    assert result.inputs['entry_binding']['status'] == 'source_bound'


@pytest.mark.parametrize('body', [
    'cls.__init__ = opaque',
    "setattr(cls, '__init__', opaque)",
    'opaque(cls)',
    'opaque()',
    'saved = cls\n        saved.__new__ = opaque',
    "setattr(cls, unknown, True)",
    "vars(cls).update({'__init__': opaque})",
    'cls.update_signature()',
    'super().__init_subclass__()',
    'registry.append(cls)',
    'yield cls',
    'if opaque:\n            cls.marker = True',
    'cls.marker = opaque.attribute',
    'cls.marker = opaque[0]',
    'cls.marker = opaque + 1',
    'cls.marker = {opaque: True}',
    "cls.marker = f'{opaque}'",
])
def test_unknown_or_structural_creation_effects_keep_the_entry_open(tmp_path, body):
    with pytest.raises(ValueError):
        analyze(tmp_path, SOURCE.replace('cls.marker = True', body))


