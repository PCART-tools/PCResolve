## @package tests.test_class_creation_hooks

import runpy

import pytest

from pcresolve import FlowAnalyzer, FunctionRef

SOURCE = '''def fixed(allowed=0): return allowed
class Base:
    def __init_subclass__(cls):
        cls.marker = True
class Public(Base):
    def __init__(self, **kwargs): fixed(**kwargs)
'''


def analyze(root, text=SOURCE, name='Public'):
    path = root / 'example.py'
    path.write_text(text, encoding='utf-8')
    return FlowAnalyzer(project_root=root).analyze(FunctionRef('example', name), max_depth=2), path


def test_a_bounded_creation_hook_preserves_the_source_constructor(tmp_path):
    result, path = analyze(tmp_path)
    binding = result.inputs['entry_binding']
    assert binding['status'] == 'source_bound'
    hooks = binding['class_creation_hooks']
    assert len(hooks) == 1
    assert hooks[0]['kind'] == 'source_class_creation_hook'
    assert hooks[0]['target']['qualname'] == 'Base.__init_subclass__'
    assert hooks[0]['receiver_class']['qualname'] == 'Public'
    assert hooks[0]['attributes'] == ['marker']
    assert hooks[0]['completion'] == 'normal_return_only'
    assert hooks[0]['phase'] == 'before_class_decorators'
    namespace = runpy.run_path(str(path))
    assert namespace['Public'].marker is True
    with pytest.raises(TypeError):
        namespace['Public'](old=1)


def test_a_source_bound_class_observer_is_not_an_unmodeled_class_escape(tmp_path):
    text = '''class Observer:
    def __init__(self, obj): self.obj = obj
    def names(self):
        return [name for name in dir(self.obj)
                if name.startswith('set_') and callable(getattr(self.obj, name))]
class Base:
    def __init_subclass__(cls): cls.names = Observer(cls).names()
class Public(Base):
    def __init__(self, **kwargs): fixed(**kwargs)
    def set_value(self, value): pass
def fixed(allowed=0): return allowed
'''
    result, _ = analyze(tmp_path, text)
    hook, = result.inputs['entry_binding']['class_creation_hooks']
    query, = hook['class_metadata_queries']
    assert hook['status'] == 'source_bound'
    assert query['query']['result_shape'] == 'native_string_list'
    assert query['input_binding']['phase'] == 'class_creation_entry'


def test_creation_hook_can_select_branches_from_source_wrapper_metadata(tmp_path):
    text = '''from functools import wraps
def mark_function(function):
    @wraps(function)
    def wrapper(value): return function(value)
    wrapper.marker = True
    return wrapper
class Base:
    def __init_subclass__(cls):
        if not hasattr(cls.draw, 'marker'): cls.draw = opaque(cls.draw)
        if not hasattr(cls.set, '_autogenerated_signature'): return
        cls.set.extra = True
class Public(Base):
    @mark_function
    def draw(self, value): return value
    def set(self, **kwargs): pass
    def __init__(self, **kwargs): fixed(**kwargs)
def fixed(allowed=0): return allowed
'''
    result, _ = analyze(tmp_path, text)
    hook = result.inputs['entry_binding']['class_creation_hooks'][0]
    queries = [item for item in hook['class_metadata_queries']
               if item.get('kind') == 'source_bound_callable_metadata_presence']
    assert [(item['method_name'], item['metadata_attribute'], item['result'])
            for item in queries] == [
                ('draw', 'marker', True),
                ('set', '_autogenerated_signature', False),
            ]
    assert hook['attributes'] == []


def test_creation_hook_can_attach_metadata_to_a_fresh_lambda_member(tmp_path):
    text = '''class Base:
    def set(self, **kwargs): pass
    @classmethod
    def update_signature(cls): cls.set.__doc__ = 'Generated setter.'
    def __init_subclass__(cls):
        cls.set = lambda self, **kwargs: Base.set(self, **kwargs)
        cls.set.__name__ = 'set'
        cls.set.__qualname__ = f"{cls.__qualname__}.set"
        cls.update_signature()
class Public(Base):
    def __init__(self, **kwargs): fixed(**kwargs)
def fixed(allowed=0): return allowed
'''
    result, _ = analyze(tmp_path, text)
    hook, = result.inputs['entry_binding']['class_creation_hooks']
    generated = [item for item in hook['class_metadata_queries']
        if item.get('kind') == 'source_bound_method_metadata_write']
    assert hook['status'] == 'source_bound'
    assert hook['attributes'] == ['set']
    assert [item['attribute'] for item in generated] == ['__name__', '__qualname__', '__doc__']
    assert all(item['generated_member_binding']['kind'] ==
        'source_class_creation_lambda_member' for item in generated)


