## @package tests.test_module_class_effects

import pytest

from pcresolve import FlowAnalyzer
from pcresolve.flow.proofs._module_class_effects import module_class_effects

SOURCE = '''class Root:
    @classmethod
    def initialize(cls): cls.names = Observer(cls).names()
    def set_value(self, value): pass
class Observer:
    def __init__(self, obj): self.obj = obj
    def names(self):
        return [name for name in dir(self.obj)
                if name.startswith('set_') and callable(getattr(self.obj, name))]
def later(): opaque(Root)
Root.initialize()
'''

DOC_HELPER_SOURCE = '''from inspect import Signature, Parameter
class Inspector:
    def __init__(self, obj): self.obj = obj
    def get_setters(self):
        return [name for name in dir(self.obj)
                if name.startswith('set_') and callable(getattr(self.obj, name))]
    def pprint_setters(self, leadingspace=4):
        return [' ' * leadingspace + name for name in self.get_setters()]
    def pprint_setters_rest(self, leadingspace=4):
        return [' ' * leadingspace + name for name in self.get_setters()]
def kwdoc(artist):
    """Render the class properties through a private inspector."""
    ai = Inspector(artist)
    return ('\\n'.join(ai.pprint_setters_rest(leadingspace=4))
            if hardcopy else
            'Properties:\\n' + '\\n'.join(ai.pprint_setters(leadingspace=4)))
hardcopy = False
class Root:
    @classmethod
    def initialize(cls):
        cls.signature = Signature([
            Parameter('self', Parameter.POSITIONAL_OR_KEYWORD),
            *[Parameter(name, Parameter.KEYWORD_ONLY, default=None)
              for name in Inspector(cls).get_setters()]])
        cls.set.__doc__ = 'Properties:\\n' + kwdoc(cls)
    def set(self, **kwargs): pass
    def set_value(self, value): pass
def later(): opaque(Root)
Root.initialize()
'''


def analyze(root, source=SOURCE):
    (root / 'example.py').write_text(source, encoding='utf-8')
    analyzer = FlowAnalyzer(project_root=root)
    analyzer._index()
    target = analyzer._definition_index.find('example', 'Root', kind='class')[0]
    body = analyzer.module_bodies['example'][0][1]
    call = body[-1].value
    return module_class_effects(analyzer, target, call)


def test_module_call_observer_uses_its_proved_prefix_not_future_source_uses(tmp_path):
    fact = analyze(tmp_path)
    assert fact['status'] == 'source_bound'
    assert fact['phase'] == 'module_initialization_call'
    assert fact['attributes'] == ['names']
    query = fact['class_metadata_queries'][0]
    assert query['input_binding']['phase'] == 'module_call_entry'
    assert query['input_binding']['creation_dependency'] == 'source_module_prefix'
    assert query['input_binding']['module_prefix'] == fact['module_prefix']
    assert fact['post_module_namespace'] == 'unproved'


def test_module_call_binds_documentation_through_a_local_observer_alias(tmp_path):
    fact = analyze(tmp_path, DOC_HELPER_SOURCE)
    assert fact is not None
    query = fact['signature_creations'][0]
    assert query['dynamic_parameters'][0]['input_query']['result_shape'] == 'native_string_list'
    documentation = next(item for item in fact['class_metadata_queries']
                         if item['kind'] == 'source_bound_class_documentation_helper')
    assert documentation['status'] == 'source_bound'
    assert set(documentation['observer_methods']) == {'pprint_setters', 'pprint_setters_rest'}
    assert documentation['output_shape'] == 'str'
    assert documentation['runtime_execution_confirmed'] is False
    assert fact['post_module_namespace'] == 'unproved'


def test_module_call_tracks_fresh_method_signature_and_metadata_writes(tmp_path):
    source = DOC_HELPER_SOURCE.replace('cls.signature = Signature([',
        "cls.set.__signature__ = Signature([").replace(
        "        cls.set.__doc__ = 'Properties:\\n' + kwdoc(cls)",
        "        cls.set.__name__ = 'set'\n"
        "        cls.set.__qualname__ = f'{cls.__qualname__}.set'\n"
        "        cls.set._autogenerated_signature = True\n"
        "        cls.set.__doc__ = 'Properties:\\n' + kwdoc(cls)")
    fact = analyze(tmp_path, source)
    assert fact is not None
    writes = [item for item in fact['class_metadata_queries']
              if item.get('kind') == 'source_bound_method_metadata_write']
    assert {item['attribute'] for item in writes} == {
        '__signature__', '__name__', '__qualname__', '_autogenerated_signature', '__doc__'}
    signature = next(item for item in writes if item['attribute'] == '__signature__')
    assert signature['value_shape'] == 'native_inspect_signature'
    assert signature['target']['qualname'] == 'Root.set'
    assert all(item['runtime_execution_confirmed'] is False for item in writes)


@pytest.mark.parametrize('old,new', [
    ("cls.set.__name__ = 'set'", 'cls.set.__name__ = opaque'),
    ("cls.set.__qualname__ = f'{cls.__qualname__}.set'", 'cls.set.__qualname__ = opaque'),
    ('cls.set._autogenerated_signature = True',
     'cls.set._autogenerated_signature = opaque'),
])
def test_module_method_metadata_writes_reject_unbound_values(tmp_path, old, new):
    source = DOC_HELPER_SOURCE.replace('cls.signature = Signature([',
        'cls.set.__signature__ = Signature([').replace(
        "        cls.set.__doc__ = 'Properties:\\n' + kwdoc(cls)",
        "        cls.set.__name__ = 'set'\n"
        "        cls.set.__qualname__ = f'{cls.__qualname__}.set'\n"
        "        cls.set._autogenerated_signature = True\n"
        "        cls.set.__doc__ = 'Properties:\\n' + kwdoc(cls)")
    assert analyze(tmp_path, source.replace(old, new)) is None


@pytest.mark.parametrize('old,new', [
    ('    ai = Inspector(artist)', '    ai = Inspector(artist)\n    opaque(artist)'),
    ('if hardcopy else', 'if artist else'),
    ('        cls.set.__doc__ = \'Properties:\\n\' + kwdoc(cls)',
     '        cls.set.__doc__ = opaque'),
])
def test_documentation_observer_rejects_class_escape_or_unmodeled_metadata_values(
        tmp_path, old, new):
    assert analyze(tmp_path, DOC_HELPER_SOURCE.replace(old, new)) is None


@pytest.mark.parametrize('old,new', [
    ('cls.names = Observer(cls).names()', 'cls.set_value = opaque; cls.names = Observer(cls).names()'),
    ('cls.names = Observer(cls).names()', 'cls.names = Observer(cls).names(); cls.set_value = opaque'),
    ('Root.initialize()', 'opaque(Root)\nRoot.initialize()'),
    ('Root.initialize()', 'Root.initialize()\nRoot.initialize()'),
    ('@classmethod', '@opaque'),
    ('def names(self):', 'def names(self):\n        opaque(self.obj)'),
])
def test_module_observer_does_not_hide_current_or_previous_effects(tmp_path, old, new):
    assert analyze(tmp_path, SOURCE.replace(old, new)) is None


DOC_QUERY = '''import inspect
from functools import lru_cache
''' + SOURCE.replace('class Observer:\n', '''class Observer:
    @staticmethod
    @lru_cache(maxsize=None)
    def alias(fn):
        text = inspect.getdoc(fn)
        if text is None: return False
        return text.startswith('Alias ')
''').replace("if name.startswith('set_') and callable(getattr(self.obj, name))]",
    "if name.startswith('set_') and callable(getattr(self.obj, name))\n"
    "                and not self.alias(getattr(self.obj, name))]")


def test_fresh_module_root_function_none_documentation_has_a_native_fallback(tmp_path):
    fact = analyze(tmp_path, DOC_QUERY)
    assert fact is not None
    members = fact['class_metadata_queries'][0]['input_binding']['matching_members']
    fallback = members[0]['documentation_resolution']
    assert fallback['kind'] == 'fresh_root_function_documentation_fallback'
    assert fallback['runtime_documentation_confirmed'] is False
    assert fallback['ancestor_namespace'] == 'builtin_object_without_matching_member'


def test_documentation_fallback_does_not_apply_to_changed_function_metadata(tmp_path):
    source = DOC_QUERY.replace('def set_value(self, value): pass',
        'def set_value(self, value): pass\n    set_value.__module__ = opaque')
    assert analyze(tmp_path, source) is None


def test_documentation_fallback_does_not_silence_a_later_setter_replacement(tmp_path):
    source = DOC_QUERY.replace('cls.names = Observer(cls).names()',
        'cls.names = Observer(cls).names(); cls.set_value = opaque')
    assert analyze(tmp_path, source) is None


def test_documentation_fallback_keeps_a_decorated_none_documentation_open(tmp_path):
    source = 'def document(fn):\n    fn.__doc__ = None\n    return fn\n' + DOC_QUERY
    source = source.replace('    def set_value(self, value):',
                            '    @document\n    def set_value(self, value):')
    assert analyze(tmp_path, source) is None


def table_source():
    return 'from inspect import Signature, Parameter\n' + SOURCE.replace('class Root:',
        "class Root:\n    excluded = ['set_hidden']").replace(
        '    def initialize(cls): cls.names = Observer(cls).names()', '''    def initialize(cls):
        cls.signature = Signature([
            *[Parameter(name, Parameter.KEYWORD_ONLY, default=None)
              for name in Observer(cls).names() if name not in Root.excluded]])''')


def test_module_signature_filter_uses_a_preserved_class_literal_sequence(tmp_path):
    fact = analyze(tmp_path, table_source())
    assert fact is not None
    condition = fact['signature_creations'][0]['dynamic_parameters'][0]['filters'][0]
    assert condition['excluded_names'] == ['set_hidden']
    assert condition['table_binding']['attribute'] == 'excluded'
    assert condition['table_binding']['phase'] == 'module_call_entry'
    assert condition['table_binding']['required_preservation'] == 'complete_current_call'


@pytest.mark.parametrize('change', [
    ('excluded = [\'set_hidden\']', 'excluded = opaque'),
    ('        cls.signature = Signature([', "        cls.excluded = []\n        cls.signature = Signature(["),
    ('        cls.signature = Signature([', "        Root.excluded.clear()\n        cls.signature = Signature(["),
    ('Root.excluded', 'opaque.excluded'),
])
def test_module_signature_filter_cannot_borrow_unproved_or_changed_class_data(tmp_path, change):
    assert analyze(tmp_path, table_source().replace(*change)) is None
